// Writes src/ui/board/icons.css, which draws Lucide icons (ISC license,
// https://lucide.dev) over Excalidraw's toolbar, its More tools menu, and its zoom and undo
// buttons. Excalidraw keeps the buttons and their behavior; only the drawn icon
// changes. Run with `node scripts/board-icons.mjs` after changing the list.
import { writeFileSync } from "node:fs";
import * as lucide from "lucide-react";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

// [CSS selector for the element that holds Excalidraw's svg, Lucide icon]
const ICONS = [
  ['[data-testid="toolbar-lock"] + .ToolIcon__icon', "LockOpen"],
  ['[data-testid="toolbar-lock"]:checked + .ToolIcon__icon', "Lock"],
  ['[data-testid="toolbar-hand"] + .ToolIcon__icon', "Hand"],
  ['[data-testid="toolbar-selection"] + .ToolIcon__icon', "MousePointer2"],
  ['[data-testid="toolbar-rectangle"] + .ToolIcon__icon', "Square"],
  ['[data-testid="toolbar-diamond"] + .ToolIcon__icon', "Diamond"],
  ['[data-testid="toolbar-ellipse"] + .ToolIcon__icon', "Circle"],
  ['[data-testid="toolbar-arrow"] + .ToolIcon__icon', "MoveRight"],
  ['[data-testid="toolbar-line"] + .ToolIcon__icon', "Minus"],
  ['[data-testid="toolbar-freedraw"] + .ToolIcon__icon', "Pencil"],
  ['[data-testid="toolbar-text"] + .ToolIcon__icon', "Type"],
  ['[data-testid="toolbar-image"] + .ToolIcon__icon', "Image"],
  ['[data-testid="toolbar-eraser"] + .ToolIcon__icon', "Eraser"],
  [".App-toolbar__extra-tools-trigger", "Ellipsis"],
  ['[data-testid="toolbar-frame"] .dropdown-menu-item__icon', "Frame"],
  [
    '.dropdown-menu-container > [data-testid="toolbar-embeddable"]:nth-child(2) .dropdown-menu-item__icon',
    "Code",
  ],
  ['[data-testid="toolbar-laser"] .dropdown-menu-item__icon', "Wand"],
  [
    '.dropdown-menu-container > [data-testid="toolbar-embeddable"]:last-child .dropdown-menu-item__icon',
    "Workflow",
  ],
  [".zoom-out-button .ToolIcon__icon", "Minus"],
  [".zoom-in-button .ToolIcon__icon", "Plus"],
  ['[data-testid="button-undo"] .ToolIcon__icon', "Undo2"],
  ['[data-testid="button-redo"] .ToolIcon__icon', "Redo2"],
];

// Icons are looked up by name from the list above, so the namespace is indexed.
const icons = { ...lucide };

const uri = (name) => {
  const svg = renderToStaticMarkup(
    createElement(icons[name], { size: 24, strokeWidth: 1.75, color: "#000" }),
  ).replace(/ class="[^"]*"/, "");
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
};

const scope = (sel) => `body .excalidraw ${sel}`;
const all = ICONS.map(([sel]) => scope(sel)).join(",\n");
let css = `/* Generated by scripts/board-icons.mjs; edit the list there, not this file.
   Lucide icons, ISC license, https://lucide.dev. */

${all} {
  display: flex;
  align-items: center;
  justify-content: center;
}

${ICONS.map(([sel]) => `${scope(sel)} > svg`).join(",\n")} {
  display: none;
}

${ICONS.map(([sel]) => `${scope(sel)}::after`).join(",\n")} {
  content: "";
  flex: none;
  width: var(--board-icon-size, 20px);
  height: var(--board-icon-size, 20px);
  background-color: currentColor;
  mask: var(--board-icon) center / contain no-repeat;
}
`;
for (const [sel, name] of ICONS) {
  if (!icons[name]) throw new Error(`no Lucide icon named ${name}`);
  css += `\n${scope(sel)} {\n  --board-icon: ${uri(name)};\n}\n`;
}
writeFileSync(new URL("../src/ui/board/icons.css", import.meta.url), css);
console.log(`wrote ${ICONS.length} icons`);
